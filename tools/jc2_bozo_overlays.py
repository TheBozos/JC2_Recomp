"""Compiles Jade Cocoon 2's code overlays for BozoEngine, offline, from the player's own disc.

JC2 loads CodeWarrior 'MWo3' modules from CDDATA.000 into fixed slots (0x940000, 0x963000, ...) and calls into them.
Each module is compiled ahead of time as an image of its own (bozo-recomp --prefix ovl_<name>), and the runtime calls
a module's code only while the 64 bytes at its load address are its header (FunctionTable::addModule: its identity).
Stages per module: tools/find_overlays.py (once: every module as the game loads it),
tools/wrap_overlay.py (an ELF at the load address; VP2S_Recomp's wrap_elf.py, JC2_WRAP_ELF), tools/overlay_functions.py
(the function map, without Ghidra), then bozo-recomp with the map as explicit entries.

  python -I tools/jc2_bozo_overlays.py <repo root> <out dir> <game dir> <bozo-recomp> <externals.txt> [batches]

Writes <out>/jc2_overlays_NN.cpp (batches including the modules' generated files) and <out>/jc2_overlays.cpp (the
registration: load address, end, identity and tables of each module). Game-derived output: it stays in build/.
"""
from pathlib import Path
import hashlib
import struct
import subprocess
import sys


def section_end(elf):
    shoff = struct.unpack_from('<I', elf, 0x20)[0]
    count = struct.unpack_from('<H', elf, 0x30)[0]
    end = 0
    for i in range(count):
        name, kind, flags, addr, off, size = struct.unpack_from('<6I', elf, shoff + 40 * i)
        if flags & 2 and addr:
            end = max(end, addr + size)
    return end


def main(root, out, game, recomp, externals, batches='32'):
    root, out, game = Path(root), Path(out), Path(game)
    batches = int(batches)
    disc, work, gen = out / 'disc', out / 'work', out / 'gen'
    for d in (disc, work, gen):
        d.mkdir(parents=True, exist_ok=True)
    py = [sys.executable, '-I']
    if not any(disc.glob('*.bin')):
        subprocess.run(py + [str(root / 'tools/find_overlays.py'), str(game / 'CDDATA.000'), str(disc)], check=True,
                       stdout=subprocess.DEVNULL)
    ovl_externals = work / 'externals.txt'
    ovl_externals.write_text(''.join(l for l in Path(externals).read_text().splitlines(True) if not l.startswith('native')))
    modules, seen, failed = [], {}, []
    for binary in sorted(disc.glob('*.bin')):
        image = binary.read_bytes()
        digest = hashlib.sha256(image).hexdigest()
        stem = binary.stem
        load = int(stem.rsplit('_', 1)[1], 16)
        name = 'ovl_' + ''.join(c if c.isalnum() or c == '_' else '_' for c in stem.rsplit('_', 1)[0])
        if digest in seen:
            continue  # the same module twice on the disc
        seen[digest] = name
        elf, csv, entries = work / f'{name}.elf', work / f'{name}.csv', work / f'{name}.entries'
        log = work / f'{name}.log'
        with log.open('w') as lf:
            ok = subprocess.run(py + [str(root / 'tools/wrap_overlay.py'), str(binary), str(elf), '--flags-from',
                                      str(game / 'SLUS_203.09')], stdout=lf, stderr=lf).returncode == 0
            ok = ok and subprocess.run(py + [str(root / 'tools/overlay_functions.py'), str(binary), str(csv)],
                                       stdout=lf, stderr=lf).returncode == 0
            if ok:
                starts = [line.split(',')[1] for line in csv.read_text().splitlines()[1:] if line.count(',') >= 3]
                entries.write_text(''.join(f'{s}\n' for s in starts))
                ok = subprocess.run([recomp, str(elf), str(gen), '--prefix', name, '--symbol-prefix', f'{name}_',
                                     '--files', '1', '--no-comments', '--externals', str(ovl_externals),
                                     '--entries', str(entries)], stdout=lf, stderr=lf).returncode == 0
        if not ok:
            failed.append(name)
            continue
        end = section_end(elf.read_bytes())
        modules.append((name, load, end, image[:64]))
    # Batches: the modules' generated files, a fixed number of translation units for the build.
    for b in range(batches):
        # Each module in a namespace of its own: the generated files of different modules share local names.
        lines = ['// Generated by tools/jc2_bozo_overlays.py: overlay modules compiled for BozoEngine.',
                 '#include "bozo/recomp.h"', '#include <cstddef>']
        for name, *_ in modules[b::batches]:
            lines += [f'namespace {name}', '{', f'#include "{name}_000.cpp"', f'#include "{name}_table.cpp"', '}']
        (out / f'jc2_overlays_{b:02d}.cpp').write_text('\n'.join(lines) + '\n')
    reg = ['// Generated by tools/jc2_bozo_overlays.py: the overlay modules for FunctionTable::addModule.',
           '#include "bozo/runtime.h"', '#include <cstddef>', '#include <cstdint>', '']
    for name, *_ in modules:
        reg += [f'namespace {name}', '{', f'extern const BozoFunctionEntry {name}_function_table[];',
                f'extern const size_t {name}_function_count;', f'extern const BozoResumeEntry {name}_resume_table[];',
                f'extern const size_t {name}_resume_count;', '}']
    reg += ['', 'struct Jc2Overlay', '{', '    uint32_t load, end;', '    uint8_t identity[64];',
            '    const BozoFunctionEntry *functions;', '    const size_t *count;', '    const BozoResumeEntry *resume;',
            '    const size_t *resumeCount;', '};', '', 'extern const Jc2Overlay jc2_overlays[] = {']
    for name, load, end, ident in modules:
        reg.append(f'    {{0x{load:x}u, 0x{end:x}u, {{{", ".join(f"0x{v:02x}" for v in ident)}}}, '
                   f'{name}::{name}_function_table, &{name}::{name}_function_count, {name}::{name}_resume_table, '
                   f'&{name}::{name}_resume_count}},')
    reg += ['};', f'extern const size_t jc2_overlay_count = {len(modules)};']
    (out / 'jc2_overlays.cpp').write_text('\n'.join(reg) + '\n')
    print(f'{len(modules)} overlay modules compiled, {len(failed)} failed' +
          (f' ({", ".join(failed[:8])}{"..." if len(failed) > 8 else ""})' if failed else ''))


if __name__ == '__main__':
    main(*sys.argv[1:])
